"""Pacific + East/Southeast Asia land and the countries in the Nvidia / Singapore story (Natural Earth 10m, public domain).
The Americas are shifted +360 deg so the Pacific map is continuous (California sits east of China)."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
from shapely.affinity import translate
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")


def shift(g):
    return translate(g, 360) if g.bounds[2] < -20 else g


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__)
        for p in getattr(g, "geoms", [g]): L.append(shift(p.buffer(0)))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        a = rec.record["ADM0_A3"]
        if a in ("CHN", "SGP", "MYS", "THA", "IDN", "USA", "TWN"):
            g = shape(rec.shape.__geo_interface__).buffer(0); adm[a] = [shift(p) for p in getattr(g, "geoms", [g])]
    data = {"wide": rings(L, box(40, -50, 300, 75), tol=0.06, min_area=0.1, nd=2),
            "fine": rings(L, box(90, -12, 130, 27), tol=0.01, min_area=0.002, nd=3)}
    for a, key, b, tol in (("CHN", "chn", box(70, 15, 140, 56), 0.05), ("SGP", "sgp", box(103, 1, 105, 2), 0.002), ("MYS", "mys", box(98, 0, 120, 8), 0.01),
                           ("THA", "tha", box(96, 5, 107, 21), 0.01), ("IDN", "idn", box(94, -12, 142, 7), 0.02), ("USA", "usa", box(230, 24, 300, 50), 0.06), ("TWN", "twn", box(119, 21, 123, 26), 0.01)):
        data[key] = rings(adm[a], b, tol=tol, min_area=0.0005 if a == "SGP" else 0.01, nd=3)
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); Americas shifted +360\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
