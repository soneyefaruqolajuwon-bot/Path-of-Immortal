"""Export map geometry (Natural Earth 10m land, public domain) to src/geo_data.js.

Produces lon/lat rings for:
  na   - North America (simplified) for the continent-wide shot
  pnw  - Salish Sea / Boundary Bay detail (lightly smoothed) for close-ups
  pr   - Point Roberts silhouette (land south of the 49th parallel on the Tsawwassen peninsula)
"""
import json
import os
import sys
import urllib.request
import zipfile

import numpy as np
import shapefile
from shapely.geometry import box, shape, Polygon, MultiPolygon

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")
URL = "https://naturalearth.s3.amazonaws.com/10m_physical/ne_10m_land.zip"
BORDER_LAT = 49.0024  # 49th parallel as surveyed at Point Roberts


def land():
    os.makedirs(CACHE, exist_ok=True)
    shp = os.path.join(CACHE, "ne_10m_land.shp")
    if not os.path.exists(shp):
        z = os.path.join(CACHE, "ne_10m_land.zip")
        if not os.path.exists(z):
            urllib.request.urlretrieve(URL, z)
        zipfile.ZipFile(z).extractall(CACHE)
    out = []
    for s in shapefile.Reader(shp).shapes():
        g = shape(s.__geo_interface__)
        out.extend(getattr(g, "geoms", [g]))
    return out


def chaikin(a, n=2):
    for _ in range(n):
        p = a[:-1]
        q = 0.75 * p + 0.25 * np.roll(p, -1, 0)
        r = 0.25 * p + 0.75 * np.roll(p, -1, 0)
        o = np.empty((len(p) * 2, 2))
        o[0::2], o[1::2] = q, r
        a = np.vstack([o, o[:1]])
    return a


def rings(geoms, clip, tol=0.0, smooth=0, min_area=0.0, nd=4):
    res = []
    for g in geoms:
        if not g.intersects(clip):
            continue
        g = g.intersection(clip)
        if tol:
            g = g.simplify(tol, preserve_topology=True)
        for p in getattr(g, "geoms", [g]):
            if not isinstance(p, Polygon) or p.area < min_area:
                continue
            a = np.asarray(p.exterior.coords)
            if smooth:
                a = chaikin(a, smooth)
            res.append([round(float(v), nd) for v in a[:-1].ravel()])
    return res


def main():
    L = land()
    na = rings(L, box(-170, 8, -48, 84), tol=0.06, min_area=0.02, nd=3)
    pnw = rings(L, box(-125.5, 47.6, -121.6, 50.3), smooth=2, min_area=0.00002)
    pr_clip = box(-123.12, 48.95, -122.99, BORDER_LAT)
    pr = rings(L, pr_clip, smooth=2)
    data = {"na": na, "pnw": pnw, "pr": pr, "borderLat": BORDER_LAT}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m land (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items() if isinstance(v, list)})


if __name__ == "__main__":
    main()
