def main():
    L = land()
    eur = rings(L, box(-25, -12, 160, 72), tol=0.06, min_area=0.05, nd=3)
    near = rings(L, box(55, 5, 125, 50), tol=0.01, min_area=0.002, smooth=1, nd=3)
    countries = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        iso = rec.record["ADM0_A3"]
        if iso in ("CHN", "IND", "NPL", "BTN", "PAK", "BGD", "MMR", "MNG", "KAZ", "AFG", "LAO", "VNM", "THA", "RUS", "IRN", "KGZ", "TJK", "UZB", "TKM"):
            g = shape(rec.shape.__geo_interface__)
            countries[iso] = rings([g], box(40, 0, 140, 60), tol=0.03, min_area=0.01, nd=3)
    data = {"eur": eur, "near": near, "countries": countries, "plateau": PLATEAU, "himalaya": HIMALAYA, "cities": CITIES}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain) + traced Tibetan Plateau outline\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(eur), len(near), {k: len(v) for k, v in countries.items()})


if __name__ == "__main__":
    main()
