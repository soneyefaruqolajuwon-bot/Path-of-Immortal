"""Export Southeast Asia geometry (Natural Earth 10m, public domain) to src/geo_data.js."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")
ISO = ["MYS", "SGP", "IDN", "BRN", "THA"]


def main():
    L = land()
    asia = rings(L, box(55, -45, 160, 50), tol=0.08, min_area=0.08, nd=2)
    sea = rings(L, box(92, -9, 126, 16), tol=0.01, smooth=1, min_area=0.0015, nd=4)
    near = rings(L, box(102.8, 0.6, 104.8, 2.2), tol=0.0008, smooth=2, min_area=0.00002, nd=5)
    countries = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        iso = rec.record["ADM0_A3"]
        if iso in ISO:
            g = shape(rec.shape.__geo_interface__)
            countries[iso] = rings([g], box(92, -9, 126, 16), tol=0.01 if iso != "SGP" else 0.0008, smooth=1, min_area=0.00002, nd=4)
    data = {"asia": asia, "sea": sea, "near": near, "countries": countries,
            "places": {"singapore": [103.82, 1.35], "kl": [101.69, 3.14], "johor": [103.76, 1.47]},
            "hubs": {"Shanghai": [121.47, 31.23], "Hong Kong": [114.17, 22.32], "Tokyo": [139.69, 35.69], "Mumbai": [72.88, 19.08],
                     "Sydney": [151.21, -33.87], "Dubai": [55.27, 25.2], "Jakarta": [106.85, -6.2]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in countries.items()}, "near", len(near), "asia", len(asia))


if __name__ == "__main__":
    main()
