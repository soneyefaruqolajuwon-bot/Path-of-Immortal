"""Egypt, Sudan, Bir Tawil and the Halaib Triangle (Natural Earth 10m, public domain).
The 1902 administrative line is a simplified outline; the 1899 line is the 22nd parallel."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape, Polygon
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
HALAIB_HINT = [(34.08, 22.0), (37.6, 22.0), (37.6, 23.4), (35.63, 23.15), (35.2, 22.92), (34.6, 22.45)]
LINE1902 = [(33.18, 21.99), (33.35, 21.88), (33.55, 21.78), (33.75, 21.74), (34.0, 21.80), (34.08, 22.0), (34.6, 22.45), (35.2, 22.92), (35.63, 23.15), (35.85, 23.17)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ("EGY", "SDN", "BRT"): adm[rec.record["ADM0_A3"]] = shape(rec.shape.__geo_interface__).buffer(0)
    hal = adm["EGY"].intersection(Polygon(HALAIB_HINT))
    data = {"wide": rings(L, box(10, 5, 55, 40), tol=0.02, min_area=0.005, nd=3), "egy": rings([adm["EGY"].difference(hal)], box(20, 15, 40, 35), tol=0.01, min_area=0.01, nd=3),
            "sdn": rings([adm["SDN"]], box(20, 5, 40, 25), tol=0.01, min_area=0.01, nd=3), "brt": rings([adm["BRT"]], box(32, 21, 35, 23), tol=0.001, nd=4),
            "hal": rings([hal], box(33, 21, 38, 24), tol=0.003, min_area=0.001, nd=4), "line1902": [[c for p in LINE1902 for c in p]]}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); 1902 line simplified\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", round(adm["BRT"].area, 3), round(hal.area, 3))


if __name__ == "__main__":
    main()
