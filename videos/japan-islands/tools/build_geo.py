"""Japan + neighbours (Natural Earth 10m, public domain) for the Japan-islands short.

Also derives:
  islets - illustrative offshore specks scattered along Japan's coast (NOT real island positions; a visual stand-in)
  eez    - a stylised 200-nautical-mile ring (median line where it meets neighbours); for illustration only
"""
import json, os, random
import numpy as np
import shapefile
from shapely.geometry import box, shape, Point
from shapely.ops import unary_union
from shapely.prepared import prep
import sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", "..", "canberra", ".cache")


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CACHE, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    jp, oth = [], []
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        g = shape(rec.shape.__geo_interface__).buffer(0)
        if g.intersects(box(110, 15, 160, 52)):
            (jp if rec.record["ADM0_A3"] == "JPN" else oth).append(g)
    J = unary_union(jp); O = unary_union(oth).intersection(box(105, 10, 170, 60))
    wide = rings(L, box(100, 5, 175, 60), tol=0.06, min_area=0.03, nd=3)
    near = rings(L, box(118, 18, 158, 50), tol=0.012, min_area=0.0004, nd=3)
    japan = rings(getattr(J, "geoms", [J]), box(110, 15, 160, 52), tol=0.012, min_area=0.0, nd=3)
    # illustrative islets along the coastline
    rnd = random.Random(7); coast = J.simplify(0.01).boundary; land = prep(J.simplify(0.01).buffer(0.02)); near_o = prep(O.simplify(0.02).buffer(0.15))
    parts = [g for g in getattr(coast, "geoms", [coast]) if g.length > 0.05]
    lens = np.array([g.length for g in parts]); cum = np.cumsum(lens) / lens.sum()
    pts = []
    while len(pts) < 1500:
        g = parts[int(np.searchsorted(cum, rnd.random()))]
        p = g.interpolate(rnd.random() * g.length)
        a, d = rnd.random() * 6.283, 0.03 + rnd.random() ** 1.7 * 0.32
        q = Point(p.x + d * np.cos(a), p.y + d * np.sin(a) * 0.8)
        if not land.contains(q) and not near_o.contains(q):
            pts.append([round(q.x, 3), round(q.y, 3), round(rnd.random(), 3)])
    # stylised EEZ: region within 200 nm (~3.33 deg) of Japan and nearer to Japan than to neighbours
    Js, Os = J.simplify(0.05).buffer(0.0), O.intersection(box(115, 15, 160, 52)).simplify(0.05)
    zone = unary_union([Js.buffer(r, 8).difference(Os.buffer(r, 8)) for r in np.linspace(0.1, 3.33, 34)]).simplify(0.05)
    zone = max(getattr(zone, "geoms", [zone]), key=lambda g: g.area) if zone.geom_type == "MultiPolygon" else zone
    eez = [[round(v, 3) for v in np.asarray(g.exterior.coords)[:-1].ravel()] for g in getattr(unary_union(zone), "geoms", [zone]) if g.area > 1]
    data = {"wide": wide, "near": near, "japan": japan, "islets": pts, "eez": eez,
            "places": {"tokyo": [139.69, 35.69], "japan": [138.5, 37.6], "pacific": [146.0, 31.5], "seaofjapan": [134.6, 40.2]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); islets and EEZ ring are illustrative\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(wide), len(near), len(japan), len(pts), len(eez))


if __name__ == "__main__":
    main()
