"""Switzerland, Liechtenstein and neighbours (Natural Earth 10m, public domain)."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        a = rec.record["ADM0_A3"]
        if a in ("CHE", "LIE", "AUT", "DEU", "FRA", "ITA"): adm[a] = shape(rec.shape.__geo_interface__).buffer(0)
    data = {"wide": rings(L, box(-12, 35, 30, 62), tol=0.03, min_area=0.02, nd=3),
            "che": rings([adm["CHE"]], box(5, 45, 11, 48.5), tol=0.003, min_area=0.001, nd=4),
            "lie": rings([adm["LIE"]], box(9, 46.8, 10, 47.4), tol=0.0005, min_area=0.0001, nd=5),
            "aut": rings([adm["AUT"]], box(8, 46, 18, 49.5), tol=0.003, min_area=0.001, nd=4)}
    for k in ("DEU", "FRA", "ITA"): data[k.lower()] = rings([adm[k]], box(4, 44, 13, 50), tol=0.004, min_area=0.001, nd=4)
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", round(adm["LIE"].area, 4), adm["LIE"].bounds)


if __name__ == "__main__":
    main()
