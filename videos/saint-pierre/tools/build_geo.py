"""Eastern Canada, Saint-Pierre and Miquelon, North America and France (Natural Earth 10m, public domain).
New France (c. 1750) is a hand-simplified outline: east of the Mississippi (to Britain, 1763) and Louisiana west of it (to Spain)."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape, Polygon
from shapely.ops import unary_union
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
EAST = [(-60, 51), (-70, 52), (-80, 52), (-90, 50.5), (-95, 49.5), (-95, 47), (-91.5, 47), (-90.5, 43), (-89.5, 37), (-90.5, 31), (-88, 30.3), (-85.5, 32), (-84, 35.5),
        (-81.5, 39), (-80, 41.5), (-77, 43.6), (-75, 45), (-71.5, 45.6), (-68.5, 47), (-65, 48.2), (-63, 49.5)]
WEST = [(-91.5, 47), (-95, 47), (-98, 49), (-104, 49), (-111, 48), (-112, 45), (-109, 41), (-105, 37), (-101, 33), (-98, 29.5), (-94, 29.5), (-90.5, 29), (-90.5, 31), (-89.5, 37), (-90.5, 43)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ("SPM", "CAN", "USA", "FRA", "GBR"):
            adm[rec.record["ADM0_A3"]] = shape(rec.shape.__geo_interface__).buffer(0)
    land = unary_union([g for g in L if g.intersects(box(-130, 10, -40, 70))])
    newfr = {"east": rings([Polygon(EAST).intersection(land)], box(-130, 10, -40, 70), tol=0.05, min_area=0.3, nd=2),
             "west": rings([Polygon(WEST).intersection(land)], box(-130, 10, -40, 70), tol=0.05, min_area=0.3, nd=2)}
    data = {"wide": rings(L, box(-135, 5, 20, 72), tol=0.06, min_area=0.05, nd=2),
            "near": rings(L, box(-70, 40, -45, 56), tol=0.003, min_area=0.00005, nd=4),
            "spm": rings([adm["SPM"]], box(-57, 46, -55.5, 47.5), tol=0.0008, nd=4),
            "france": rings([adm["FRA"]], box(-6, 41, 10, 52), tol=0.02, min_area=0.01, nd=3),
            "newfr": newfr,
            "places": {"stpierre": [-56.18, 46.78], "miquelon": [-56.33, 47.05], "fortune": [-55.83, 47.07], "banks": [-51.0, 45.0], "paris": [2.35, 48.86],
                       "newfoundland": [-56.2, 48.6], "canada": [-66.5, 50.2], "atlantic": [-50.5, 44.0]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); New France outline is hand-simplified\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items() if isinstance(v, list)}, {k: len(v) for k, v in newfr.items()})


if __name__ == "__main__":
    main()
