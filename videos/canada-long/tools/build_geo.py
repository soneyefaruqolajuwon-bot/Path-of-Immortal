"""North America + the North Atlantic + Scandinavia (Natural Earth 10m, public domain) for the Canada pair (Part 1 short + Part 2 long-form).
The Canadian Shield, the Hudson Bay Lowlands (cut out of it) and the southern permafrost limit are hand-simplified outlines.
Small-town lights are illustrative; big cities are real (listed in app.js)."""
import json, os, random, sys
import shapefile
from shapely.geometry import box, shape, Polygon, Point
from shapely.ops import unary_union
from shapely.prepared import prep
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache"); LC = os.path.join(HERE, "..", ".cache")
SHIELD = [(-55.7, 52.2), (-57.5, 50.6), (-60.5, 50.2), (-64.5, 50.0), (-67.5, 49.3), (-70.0, 47.6), (-72.5, 46.6), (-75.5, 45.6), (-77.5, 45.0), (-79.8, 44.9), (-81.4, 46.0),
          (-84.5, 46.7), (-88.5, 48.3), (-92.5, 48.7), (-95.5, 49.4), (-96.5, 50.8), (-98.0, 53.5), (-101.5, 55.0), (-106.0, 56.8), (-110.5, 58.6), (-113.5, 60.5), (-117.0, 62.0),
          (-120.5, 65.0), (-122.5, 67.5), (-118.0, 69.5), (-108.0, 69.0), (-96.0, 71.5), (-86.0, 72.5), (-78.0, 74.0), (-66.0, 70.0), (-61.0, 64.0), (-60.5, 58.0), (-56.5, 54.0)]
LOWLANDS = [(-95.5, 59.2), (-93.0, 57.4), (-89.0, 56.6), (-84.5, 55.4), (-81.6, 53.6), (-79.6, 51.4), (-81.5, 50.3), (-85.5, 50.9), (-89.5, 52.6), (-93.0, 54.8), (-95.0, 56.8)]
PERMA = [(-141, 60.3), (-132, 58.8), (-124, 58.2), (-117, 57.6), (-110, 57.9), (-103, 56.4), (-97, 55.6), (-92, 54.3), (-88, 52.6), (-82, 51.2), (-77, 51.0), (-72, 51.6), (-66, 52.4), (-60, 53.6), (-56, 53.4)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ("CAN", "USA", "SWE", "NOR", "FIN"): adm[rec.record["ADM0_A3"]] = shape(rec.shape.__geo_interface__).buffer(0)
    lakes = []
    for rec in shapefile.Reader(os.path.join(LC, "ne_10m_lakes.shp")).shapeRecords():
        g = shape(rec.shape.__geo_interface__)
        if g.intersects(box(-125, 40, -60, 70)) and g.area > 0.5: lakes.append(g.buffer(0))
    can = adm["CAN"]; land = unary_union([g for g in L if g.intersects(box(-142, 41, -52, 84))])
    shield = Polygon(SHIELD).difference(Polygon(LOWLANDS)).intersection(can.buffer(0.02)).difference(unary_union(lakes))
    usmain = adm["USA"].intersection(box(-126, 24, -66, 50))
    rnd = random.Random(3); towns = []; cp = prep(can.intersection(box(-130, 42, -52, 54.5))); up = prep(usmain)
    while len(towns) < 700:   # illustrative small-town lights: dense along the southern band, plus the US
        lon, lat = rnd.uniform(-128, -53), rnd.uniform(25, 54)
        w = 1.0 if lat < 50 else 0.35
        if rnd.random() > w: continue
        q = Point(lon, lat)
        if (cp.contains(q) and rnd.random() < 0.55) or (up.contains(q) and rnd.random() < 0.45): towns.append([round(lon, 2), round(lat, 2), round(rnd.random(), 2)])
    data = {"wide": rings(L, box(-170, 15, 45, 84), tol=0.05, min_area=0.03, nd=2),
            "lakes": rings(lakes, box(-130, 38, -55, 72), tol=0.02, min_area=0.3, nd=3),
            "can": rings([can], box(-142, 41, -52, 84), tol=0.03, min_area=0.05, nd=3),
            "usa": rings([usmain], box(-130, 20, -60, 52), tol=0.03, min_area=0.05, nd=3),
            "scandi": rings([adm["SWE"], adm["NOR"], adm["FIN"]], box(0, 54, 35, 72), tol=0.03, min_area=0.05, nd=3),
            "shield": rings([shield], box(-142, 41, -52, 84), tol=0.05, min_area=0.3, nd=3),
            "perma": [[c for p in PERMA for c in p]], "towns": towns,
            "places": {"oslo": [10.75, 59.91], "stockholm": [18.07, 59.33], "helsinki": [24.94, 60.17], "yellowknife": [-114.37, 62.45], "hudson": [-85.5, 59.5],
                       "acasta": [-115.5, 65.2], "sudbury": [-81.0, 46.5], "timmins": [-81.33, 48.48], "athabasca": [-105.0, 57.76], "diavik": [-110.3, 64.5], "valdor": [-77.8, 48.1], "thompson": [-97.85, 55.74]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); Shield, lowlands and permafrost limit are simplified outlines\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items() if isinstance(v, list)})


if __name__ == "__main__":
    main()
