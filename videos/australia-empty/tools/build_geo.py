"""Australia + contiguous US (Natural Earth 10m, public domain) for the 'empty middle of Australia' short.
  usOnAus - the lower-48 outline moved onto Australia at true scale (km offsets from each centroid), for the size comparison
  towns   - illustrative small-town lights scattered along the populated coasts (big cities are real, listed in app.js)"""
import json, math, os, random, sys
import numpy as np, shapefile
from shapely.geometry import box, shape, Point
from shapely.ops import unary_union
from shapely.prepared import prep
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); V = os.path.join(HERE, "..", "..")
CB, FB = os.path.join(V, "canberra", ".cache"), os.path.join(V, "france-brazil", ".cache")


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    aus = [g for g in L if g.intersects(box(112, -44, 154, -10)) and g.area > 0.002]
    A = unary_union([g for g in aus if g.intersects(box(112, -40, 154, -10))])
    Amain = max(A.geoms, key=lambda g: g.area) if A.geom_type == "MultiPolygon" else A
    wide = rings(L, box(95, -50, 180, 5), tol=0.03, min_area=0.01, nd=3)
    usland = rings(L, box(-135, 15, -55, 55), tol=0.03, min_area=0.02, nd=3)
    us = None
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] == "USA":
            us = shape(rec.shape.__geo_interface__).buffer(0).intersection(box(-125, 24, -66, 50))
    us = max(us.geoms, key=lambda g: g.area).simplify(0.04)
    uc, ac = us.centroid, Amain.centroid
    def move(lon, lat):
        x = (lon - uc.x) * math.cos(math.radians(lat)); y = lat - uc.y          # degrees of arc ~ km/111
        nlat = ac.y + y; return [round(ac.x + x / math.cos(math.radians(nlat)), 3), round(nlat, 3)]
    usOnAus = [v for p in np.asarray(us.exterior.coords)[:-1] for v in move(*p)]
    interior = Amain.simplify(0.05).buffer(-3.2).buffer(1.2).simplify(0.05)
    interior = [[round(v, 3) for v in np.asarray(g.exterior.coords)[:-1].ravel()] for g in getattr(interior, "geoms", [interior]) if g.area > 1]
    rivers = {}
    for rec in shapefile.ShapeRecords if False else shapefile.Reader(os.path.join(FB, "ne_10m_rivers_lake_centerlines.shp")).shapeRecords():
        n = rec.record["name"]
        if n in ("Mississippi", "Missouri", "Ohio", "Murray", "Darling"):
            g = shape(rec.shape.__geo_interface__).simplify(0.03)
            for ln in getattr(g, "geoms", [g]):
                rivers.setdefault(n, []).append([round(v, 3) for v in np.asarray(ln.coords).ravel()])
    # illustrative small-town lights hugging the populated coasts
    rnd = random.Random(5); coast = Amain.simplify(0.02).exterior; land = prep(Amain)
    towns = []
    while len(towns) < 420:
        p = coast.interpolate(rnd.random() * coast.length)
        w = 1.0 if (p.x > 145 and p.y < -15) else 0.85 if (p.x < 118 and p.y < -30) else 0.7 if (p.y < -33) else 0.12
        if rnd.random() > w: continue
        q = Point(p.x + rnd.gauss(0, 0.6), p.y + rnd.gauss(0, 0.5))
        if land.contains(q): towns.append([round(q.x, 2), round(q.y, 2), round(rnd.random(), 2)])
    data = {"wide": wide, "usland": usland, "usOnAus": [usOnAus], "aus": rings([Amain], box(100, -50, 160, 0), tol=0.02, nd=3),
            "interior": interior, "rivers": rivers, "towns": towns}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); small-town lights are illustrative\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(wide), len(usland), len(towns), {k: len(v) for k, v in rivers.items()}, len(interior))


if __name__ == "__main__":
    main()
