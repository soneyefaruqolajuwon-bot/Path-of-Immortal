"""Land + the countries in the six accidental-invasion stories (Natural Earth 10m, public domain).
The Aleutians (Kiska) are also stored shifted by -360 deg so they sit next to Alaska in a Pacific-centred view."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
from shapely.affinity import translate
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    want = ("CHE", "LIE", "AUT", "ESP", "GIB", "NIC", "CRI", "GRC", "BGR", "MKD", "DEU", "FRA", "ITA", "PRT")
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        a = rec.record["ADM0_A3"]
        if a in want: adm[a] = shape(rec.shape.__geo_interface__).buffer(0)
    world = rings(L, box(-180, -58, 180, 80), tol=0.15, min_area=0.6, nd=1)
    aleut = [translate(g, -360, 0) for g in L if g.intersects(box(165, 48, 180, 58))]
    data = {"wide": world + rings(aleut, box(-195, 48, -180, 58), tol=0.03, min_area=0.002, nd=2),
            "eu": rings(L, box(-12, 34, 32, 58), tol=0.02, min_area=0.005, nd=3),
            "fine_gib": rings(L, box(-5.8, 35.9, -5.0, 36.5), tol=0.0006, min_area=0.00001, nd=4),
            "fine_cr": rings(L, box(-84.6, 10.2, -83.0, 11.6), tol=0.001, min_area=0.0001, nd=4),
            "fine_kiska": rings(aleut, box(-183.2, 51.6, -181.8, 52.4), tol=0.001, min_area=0.0001, nd=4)}
    clips = {"CHE": (5, 45, 11, 48.5), "LIE": (9, 46.8, 10, 47.4), "AUT": (8, 46, 18, 49.5), "ESP": (-10, 35.5, 5, 44.5), "GIB": (-5.6, 36, -5.2, 36.3), "NIC": (-88, 10.5, -82.5, 15.5), "CRI": (-86, 8, -82.5, 11.3),
             "GRC": (19, 34.5, 29, 42), "BGR": (22, 41, 29, 44.5), "MKD": (20, 40.8, 23.2, 42.5), "DEU": (5, 47, 15, 55), "FRA": (-5, 42, 9, 51.5), "ITA": (6, 36, 19, 47.5), "PRT": (-10, 36.8, -6, 42.2)}
    for a, bb in clips.items():
        data[a.lower()] = rings([adm[a]], box(*bb), tol=0.0006 if a in ("GIB", "LIE") else 0.004, min_area=0.00001, nd=4)
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
