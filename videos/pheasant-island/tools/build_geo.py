"""France, Spain and the Basque border (Natural Earth 10m, public domain) for the Pheasant Island short."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ("FRA", "ESP"): adm[rec.record["ADM0_A3"]] = shape(rec.shape.__geo_interface__).buffer(0)
    data = {"wide": rings(L, box(-14, 33, 16, 56), tol=0.02, min_area=0.002, nd=3),
            "near": rings(L, box(-3.5, 42.6, 0.2, 44.0), tol=0.002, min_area=0.00001, nd=4),
            "fra": rings([adm["FRA"]], box(-6, 41, 10, 52), tol=0.01, min_area=0.01, nd=3), "esp": rings([adm["ESP"]], box(-10, 35, 5, 44.5), tol=0.01, min_area=0.01, nd=3),
            "places": {"island": [-1.7616, 43.3428], "irun": [-1.789, 43.338], "hendaye": [-1.775, 43.358], "madrid": [-3.70, 40.42], "paris": [2.35, 48.86]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB")


if __name__ == "__main__":
    main()
