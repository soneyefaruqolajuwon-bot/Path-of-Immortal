"""World land, India, the southern-hemisphere land, and continents (for the drift animation). Natural Earth 10m, public domain."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
from shapely.ops import unary_union
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
W = box(-180, -85, 180, 84)


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    cont, ind = {}, None
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        g = shape(rec.shape.__geo_interface__).buffer(0); r = rec.record
        if r["ADM0_A3"] == "IND": ind = g
        cont.setdefault(r["CONTINENT"], []).append(g)
    land = unary_union([g.buffer(0) for g in L])
    data = {"wide": rings(L, W, tol=0.18, min_area=1.0, nd=1),
            "south": rings([land], box(-180, -85, 180, 0), tol=0.18, min_area=1.0, nd=1),
            "north": rings([land], box(-180, 0, 180, 84), tol=0.18, min_area=1.0, nd=1),
            "india": rings([ind], W, tol=0.05, min_area=0.1, nd=2)}
    keymap = {"North America": "c_na", "South America": "c_sa", "Europe": "c_eu", "Asia": "c_as", "Africa": "c_af", "Oceania": "c_oc", "Antarctica": "c_an"}
    for k, v in keymap.items():
        u = unary_union(cont[k])
        data[v] = rings([u], W, tol=0.2, min_area=1.0, nd=1)
    data["c_eurasia"] = rings([unary_union(cont["Europe"] + cont["Asia"])], W, tol=0.12, min_area=3, nd=2)
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    a_n, a_s = land.intersection(box(-180, 0, 180, 90)).area, land.intersection(box(-180, -90, 180, 0)).area
    print(out, os.path.getsize(out) // 1024, "KB")


if __name__ == "__main__":
    main()
