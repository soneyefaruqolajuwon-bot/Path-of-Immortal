"""Canada, its neighbours, its lakes, the Laurentide/Cordilleran ice sheet and stylised 'cheese' ponds (Natural Earth 10m, public domain).
Real lakes = NE 10m lakes + the NE North America lakes supplement. The extra small ponds are a stylised stand-in for the
~880,000 lakes too small to draw at this zoom; they are only placed on Canadian Shield land. The ice extent is hand-traced (LGM, approx.)."""
import json, os, random, sys
import shapefile
from shapely.geometry import box, shape, Polygon, Point
from shapely.ops import unary_union
from shapely.prepared import prep
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
LK = [os.path.join(HERE, "..", "..", "canada-long", ".cache", "ne_10m_lakes"), os.path.join(HERE, "..", ".cache", "ne_10m_lakes_north_america")]
SHIELD = [(-123, 66.5), (-118, 62), (-112, 58.5), (-104, 55), (-98, 52), (-96, 49.6), (-90, 48.3), (-85, 46.8), (-80.5, 45.2), (-76, 44.4), (-73, 45.8),
          (-69, 47.8), (-64, 49.8), (-57, 51.2), (-55.5, 53), (-61, 57), (-64.5, 60.3), (-70, 62.5), (-78, 62.3), (-80, 60), (-82, 55), (-87, 56), (-94, 59),
          (-91, 64), (-85, 67), (-76, 68), (-68, 67), (-62, 66.5), (-66, 70), (-80, 73.5), (-90, 70), (-98, 69), (-110, 68.5), (-118, 68)]
ICE = [(-135, 56), (-128, 50.5), (-124, 47.6), (-121, 47.2), (-114, 48.4), (-108, 48), (-100, 46.2), (-97, 43.2), (-93, 42.2), (-89, 41), (-86, 39.4), (-84, 39.1),
       (-81, 40.9), (-77, 41.6), (-74, 40.6), (-70, 41.3), (-65, 43.2), (-60, 45.2), (-55, 46.4), (-51.5, 48), (-54, 53), (-59.5, 58), (-63.5, 61), (-61.5, 64.5),
       (-63, 67.5), (-68, 71), (-74, 75), (-71, 78.2), (-62, 81.2), (-70, 83.2), (-95, 82.6), (-120, 78.8), (-126, 74.5), (-131, 70.3), (-138, 69.4), (-136, 66),
       (-138, 63), (-139.5, 60), (-135, 56)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    can = None
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] == "CAN": can = shape(rec.shape.__geo_interface__).buffer(0)
    lakes = []
    for f in LK:
        for s in shapefile.Reader(f).shapes():
            g = shape(s.__geo_interface__).buffer(0)
            if g.intersects(can): lakes.append(g)
    lk = unary_union(lakes).intersection(can.buffer(0.05))
    # stylised ponds on Shield land (not inside an existing lake)
    sh = prep(Polygon(SHIELD).intersection(can).difference(lk.buffer(0.05)))
    rnd = random.Random(7); ponds = []
    while len(ponds) < 1500 * 3:
        lo, la = rnd.uniform(-124, -55), rnd.uniform(44, 74)
        if sh.contains(Point(lo, la)):
            ponds += [round(lo, 2), round(la, 2), round(rnd.uniform(0.35, 1.0), 2)]
    data = {"wide": rings(L, box(-180, 20, -10, 84), tol=0.08, min_area=0.15, nd=2),
            "can": rings([can], box(-142, 41, -50, 84), tol=0.06, min_area=0.12, nd=2),
            "lakes": rings([lk], box(-142, 41, -50, 84), tol=0.025, min_area=0.004, nd=2),
            "ice": [[c for p in ICE for c in p]], "ponds": ponds}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); ice extent hand-traced, small ponds stylised\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(data["lakes"]), "lake rings", len(ponds) // 3, "ponds")


if __name__ == "__main__":
    main()
