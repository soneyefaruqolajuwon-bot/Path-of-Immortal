"""Export South America geometry (Natural Earth 10m, public domain) to src/geo_data.js."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")
BOX = box(-95, -57, -30, 15)
ISO = ["VEN", "COL", "PAN", "ECU", "PER", "BOL", "BRA", "ARG", "CHL", "PRY", "URY", "GUY", "SUR", "CRI"]


def main():
    L = land()
    land_r = rings(L, BOX, tol=0.03, smooth=1, min_area=0.02, nd=3)
    countries = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        iso = rec.record["ADM0_A3"]
        if iso in ISO:
            countries[iso] = rings([shape(rec.shape.__geo_interface__)], BOX, tol=0.03, smooth=1, min_area=0.02, nd=3)
        if iso == "FRA":
            countries["GUF"] = rings([shape(rec.shape.__geo_interface__)], box(-55, 1.5, -51, 6.2), tol=0.02, min_area=0.02, nd=3)
    data = {"land": land_r, "countries": countries,
            "cities": {"caracas": [-66.9, 10.5], "bogota": [-74.07, 4.71], "quito": [-78.47, -0.18], "lima": [-77.04, -12.05],
                       "lapaz": [-68.15, -16.5], "sucre": [-65.26, -19.04], "panama": [-79.52, 8.98]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in countries.items()})


if __name__ == "__main__":
    main()
