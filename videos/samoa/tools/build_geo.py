"""South Pacific geometry (Natural Earth 10m, public domain) in 0..360 longitudes (no antimeridian wrap)."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__)); CACHE = os.path.join(HERE, "..", ".cache")
E360 = lambda x: x + 360 if x < 0 else x


def shift(rs):
    out = []
    for r in rs:
        if max(r[0::2]) <= 0.0:
            r = [v + 360 if i % 2 == 0 else v for i, v in enumerate(r)]
        out.append([round(v, 4) for v in r])
    return out


def both(geoms, tol, min_area, smooth=0):
    return shift(rings(geoms, box(110, -50, 180, 10), tol=tol, min_area=min_area, smooth=smooth, nd=4) +
                 rings(geoms, box(-180, -50, -140, 10), tol=tol, min_area=min_area, smooth=smooth, nd=4))


def main():
    L = land()
    pac = both(L, 0.02, 0.003)
    near = both(L, 0.002, 0.00002, smooth=1)
    countries = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        iso = rec.record["ADM0_A3"]
        if iso in ("AUS", "NZL", "WSM", "ASM", "FJI", "TON"):
            g = shape(rec.shape.__geo_interface__)
            small = iso in ("WSM", "ASM")
            countries[iso] = both([g], 0.002 if small else 0.02, 0.00002 if small else 0.003, smooth=1 if small else 0)
    # current (post-2011) Date Line south of the Kiribati jog
    pts = []
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_geographic_lines.shp")).shapeRecords():
        if rec.record["name"] == "International Date Line":
            pts = rec.shape.points
    i0 = next(i for i, (x, y) in enumerate(pts) if abs(x + 169.4) < 0.05 and abs(y + 5.84) < 0.05)
    new = [(E360(x), y) for x, y in pts[i0:] if y > -50]
    j = next((k for k in range(1, len(new)) if new[k][1] > new[k - 1][1] + 5), len(new))
    new = new[:j]
    new = [(180.0, -2.0), (190.6, -5.84)] + new
    data = {"pac": pac, "near": near, "countries": countries, "idlNew": [[round(x, 3), round(y, 3)] for x, y in new],
            "places": {"apia": [E360(-171.76), -13.83], "pago": [E360(-170.70), -14.28], "sydney": [151.21, -33.87], "auckland": [174.76, -36.85],
                       "samoa": [E360(-172.1), -13.75]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); longitudes in 0..360\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in countries.items()}, "idl pts", len(new), new[:3], new[-3:])


if __name__ == "__main__":
    main()
