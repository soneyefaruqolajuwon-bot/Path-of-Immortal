"""Export West Africa geometry (Natural Earth 10m, public domain) to src/geo_data.js."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")
BOX = box(-26.0, 3.0, 4.0, 28.0)
ISO = ["GMB", "SEN", "GNB", "GIN", "MLI", "MRT"]

def main():
    L = land()
    land_r = rings(L, BOX, tol=0.003, smooth=1, min_area=0.0005, nd=4)
    countries = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ISO:
            countries[rec.record["ADM0_A3"]] = rings([shape(rec.shape.__geo_interface__)], BOX, tol=0.002, smooth=1, min_area=0.0005, nd=4)
    river = []
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_rivers_lake_centerlines.shp")).shapeRecords():
        if "Gambia" in (rec.record["name"] or ""):
            g = shape(rec.shape.__geo_interface__)
            for ln in getattr(g, "geoms", [g]):
                river.append([round(v, 4) for xy in ln.coords for v in xy])
    from shapely.geometry import LineString, MultiLineString
    from shapely.ops import linemerge
    merged = linemerge(MultiLineString([LineString(list(zip(r[0::2], r[1::2]))) for r in river]))
    lines = list(getattr(merged, "geoms", [merged]))
    main_line = max(lines, key=lambda l: l.intersection(box(-16.8, 13.0, -13.7, 13.9)).length)
    seg = main_line.intersection(box(-16.75, 13.0, -13.75, 13.95))
    seg = max(getattr(seg, "geoms", [seg]), key=lambda l: l.length)
    pts = list(seg.coords)
    if pts[0][0] > pts[-1][0]:
        pts = pts[::-1]
    estuary = [(-16.66, 13.48), (-16.5, 13.43), (-16.25, 13.39), (-16.0, 13.41), (-15.75, 13.43), (-15.52, 13.47)]
    pts = estuary + pts      # Natural Earth's centerline starts above the estuary; lead in from the mouth at Banjul
    route = [round(v, 4) for xy in pts for v in xy]
    print("route pts", len(pts), pts[0], pts[-1])
    data = {"route": route, "land": land_r, "countries": countries, "river": river, "banjul": [-16.58, 13.45], "yarbutenda": [-13.8, 13.62]}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in countries.items()}, "river parts", len(river), [len(r)//2 for r in river])

if __name__ == "__main__":
    main()
