"""Americas land, Panama/Colombia, the Darién Gap, the Panama Canal and the Pan-American Highway (Natural Earth 10m, public domain).
The highway and canal are hand-traced through real cities/locks (accurate at these zooms); the gap region is simplified."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape, Polygon
from shapely.ops import unary_union
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
HWY_N = [(-148.4, 70.25), (-147.7, 64.8), (-143.0, 63.3), (-135.05, 60.7), (-120.2, 55.8), (-113.5, 53.5), (-114.0, 51.0), (-111.3, 47.5), (-105.0, 39.7), (-106.4, 31.8),
         (-106.1, 28.6), (-103.3, 25.5), (-99.1, 19.4), (-96.7, 17.1), (-93.1, 16.75), (-90.5, 14.6), (-89.2, 13.7), (-86.3, 12.1), (-84.1, 9.9), (-82.4, 8.4), (-80.4, 8.2), (-79.5, 9.0), (-79.1, 9.17), (-78.4, 8.75), (-77.69, 8.16)]
HWY_S = [(-76.73, 8.09), (-75.57, 6.25), (-76.5, 3.45), (-77.3, 1.2), (-78.5, -0.2), (-79.9, -2.2), (-79.0, -8.1), (-77.0, -12.0), (-71.5, -16.4), (-70.3, -18.5), (-70.4, -23.6), (-70.65, -33.45),
         (-68.8, -32.9), (-64.2, -33.1), (-58.4, -34.6), (-62.3, -38.7), (-65.0, -42.8), (-67.5, -45.9), (-69.2, -51.6), (-68.3, -54.8)]
CANAL = [(-79.92, 9.38), (-79.92, 9.27), (-79.83, 9.17), (-79.70, 9.12), (-79.65, 9.05), (-79.59, 9.00), (-79.57, 8.95)]
GAP = [(-78.25, 8.95), (-77.5, 8.85), (-77.0, 8.55), (-76.75, 8.1), (-76.9, 7.4), (-77.6, 7.2), (-78.15, 7.6), (-78.35, 8.3)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        r = rec.record; adm.setdefault(r["CONTINENT"], []).append(shape(rec.shape.__geo_interface__).buffer(0))
        if r["ADM0_A3"] in ("PAN", "COL"): adm[r["ADM0_A3"]] = shape(rec.shape.__geo_interface__).buffer(0)
    land = unary_union([g.buffer(0) for g in L if g.intersects(box(-170, -60, -30, 75))])
    gap = land.intersection(Polygon(GAP))
    data = {"wide": rings(L, box(-180, -60, 40, 84), tol=0.12, min_area=0.5, nd=2),
            "fine": rings(L, box(-86, 2, -72, 14), tol=0.004, min_area=0.002, nd=3),
            "pan": rings([adm["PAN"]], box(-84, 6, -76, 10.5), tol=0.005, min_area=0.002, nd=3),
            "col": rings([adm["COL"]], box(-80, -5, -66, 14), tol=0.01, min_area=0.01, nd=3),
            "na": rings([unary_union(adm["North America"])], box(-180, 5, -25, 84), tol=0.15, min_area=0.5, nd=2),
            "sa": rings([unary_union(adm["South America"])], box(-95, -60, -30, 15), tol=0.12, min_area=0.5, nd=2),
            "gap": rings([gap], box(-79, 7, -76, 9.5), tol=0.003, min_area=0.001, nd=3),
            "hwy_n": [[c for p in HWY_N for c in p]], "hwy_s": [[c for p in HWY_S for c in p]], "canal": [[c for p in CANAL for c in p]]}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); highway/canal hand-traced\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", round(gap.area, 3))


if __name__ == "__main__":
    main()
