"""Canada's three territories + Mexico moved onto Nunavut at true scale (Natural Earth 10m, public domain) -> src/geo_extra.js"""
import json, math, os, sys
import numpy as np, shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")


def main():
    terr = {}
    for rec in shapefile.Reader(os.path.join(CB, "adm1", "ne_10m_admin_1_states_provinces.shp")).shapeRecords():
        if rec.record["adm0_a3"] == "CAN" and rec.record["name"] in ("Yukon", "Northwest Territories", "Nunavut"):
            terr[rec.record["name"]] = shape(rec.shape.__geo_interface__).buffer(0)
    mex = None
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] == "MEX": mex = shape(rec.shape.__geo_interface__).buffer(0)
    mex = max(mex.geoms, key=lambda g: g.area).simplify(0.04)
    mc, nc = mex.centroid, (-92.0, 66.5)          # put Mexico over Nunavut's mainland + Kivalliq
    def move(lon, lat):
        x = (lon - mc.x) * math.cos(math.radians(lat)); y = lat - mc.y; nlat = nc[1] + y
        return [round(nc[0] + x / math.cos(math.radians(nlat)), 3), round(nlat, 3)]
    data = {"terr": {k: rings([v], box(-142, 55, -50, 84), tol=0.04, min_area=0.3, nd=3) for k, v in terr.items()},
            "mexOnNu": [[c for p in np.asarray(mex.exterior.coords)[:-1] for c in move(*p)]]}
    out = os.path.join(HERE, "..", "src", "geo_extra.js")
    open(out, "w").write("// generated by tools/build_geo_extra.py (Natural Earth 10m, public domain)\nconst GEOX = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data["terr"].items()})


if __name__ == "__main__":
    main()
