"""Australia + states (Natural Earth 10m, public domain) for the Canberra short."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CACHE = os.path.join(HERE, "..", ".cache")
STATES = {"New South Wales": "NSW", "Victoria": "VIC", "Australian Capital Territory": "ACT", "Queensland": "QLD", "South Australia": "SA",
          "Tasmania": "TAS", "Western Australia": "WA", "Northern Territory": "NT", "Jervis Bay Territory": "JBT"}


def main():
    L = land()
    world = rings(L, box(108, -47, 160, -8), tol=0.006, min_area=0.0005, smooth=1, nd=4)
    states = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "adm1", "ne_10m_admin_1_states_provinces.shp")).shapeRecords():
        if rec.record["adm0_a3"] != "AUS": continue
        code = STATES.get(rec.record["name"])
        if not code: continue
        g = shape(rec.shape.__geo_interface__).buffer(0)
        fine = code in ("ACT", "NSW", "VIC", "JBT")
        states[code] = rings([g], box(100, -50, 180, 0), tol=0.004 if code == "ACT" else (0.01 if fine else 0.04), min_area=0.0 if code in ("ACT", "JBT") else 0.002, nd=4)
    data = {"world": world, "africa": states, "europe": {},
            "places": {"sydney": [151.21, -33.87], "melbourne": [144.96, -37.81], "canberra": [149.13, -35.28], "dalgety": [148.83, -36.50],
                       "yass": [148.91, -34.84], "jervis": [150.70, -35.12], "albury": [146.92, -36.08], "bombala": [149.24, -36.91], "orange": [149.10, -33.28],
                       "armidale": [151.65, -30.51], "tumut": [148.22, -35.30], "lyndhurst": [149.05, -33.67]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(world), {k: len(v) for k, v in states.items()})


if __name__ == "__main__":
    main()
