"""World land, a finer Suez / Red Sea set and a fine Istanbul set (Natural Earth 10m, public domain); the canal is hand-traced."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
CANAL = [(32.31, 31.27), (32.32, 31.0), (32.30, 30.75), (32.28, 30.58), (32.33, 30.45), (32.40, 30.33), (32.50, 30.20), (32.56, 30.05), (32.56, 29.93)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    data = {"wide": rings(L, box(-30, -45, 140, 70), tol=0.08, min_area=0.1, nd=2),
            "mid": rings(L, box(20, 8, 50, 46), tol=0.01, min_area=0.005, nd=3),
            "ist": rings(L, box(28.4, 40.7, 29.8, 41.5), tol=0.001, min_area=0.00002, nd=4),
            "canal": [[c for p in CANAL for c in p]]}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); Suez Canal hand-traced\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
