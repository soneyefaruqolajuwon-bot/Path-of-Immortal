"""World land plus fine regional sets for the six chokepoints (Natural Earth 10m, public domain); canals + the Bosporus are hand-traced."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
REGIONS = {"bos": (18, 34, 45, 48), "bsea": (6, 28, 60, 54), "pan": (-86, 4, -73, 14), "bab": (33, 5, 54, 20), "sue": (16, 18, 48, 40), "mal": (88, -8, 114, 12), "hor": (46, 19, 66, 33)}
LINES = {"suezc": [(32.31, 31.27), (32.32, 31.0), (32.30, 30.75), (32.28, 30.58), (32.33, 30.45), (32.40, 30.33), (32.50, 30.20), (32.56, 30.05), (32.56, 29.93)],
         "panc": [(-79.92, 9.38), (-79.92, 9.27), (-79.83, 9.17), (-79.70, 9.12), (-79.65, 9.05), (-79.59, 9.00), (-79.57, 8.95)],
         "bosp": [(29.12, 41.24), (29.08, 41.17), (29.05, 41.11), (29.02, 41.06), (28.99, 41.01)]}


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    data = {"wide": rings(L, box(-180, -60, 180, 80), tol=0.12, min_area=0.3, nd=2)}
    for k, b in REGIONS.items():
        data[k] = rings(L, box(*b), tol=0.02 if k == "bsea" else 0.008, min_area=0.002 if k == "bsea" else 0.0005, nd=3)
    for k, pts in LINES.items():
        data[k] = [[c for p in pts for c in p]]
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); canals + Bosporus hand-traced\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\nconst REGIONS = " + json.dumps(REGIONS) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items()})


if __name__ == "__main__":
    main()
