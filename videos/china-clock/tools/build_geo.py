"""China, neighbours and the contiguous US (Natural Earth 10m, public domain) for the one-clock short.
  usOnChina - the lower-48 outline moved onto China at true scale (arc offsets from each centroid), for the width comparison"""
import json, math, os, sys
import numpy as np, shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    adm = {}
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ("CHN", "USA"): adm[rec.record["ADM0_A3"]] = shape(rec.shape.__geo_interface__).buffer(0)
    chn = adm["CHN"]; cmain = max(chn.geoms, key=lambda g: g.area) if chn.geom_type == "MultiPolygon" else chn
    us = adm["USA"].intersection(box(-125, 24, -66, 50)); us = max(us.geoms, key=lambda g: g.area).simplify(0.05)
    uc, cc = us.centroid, cmain.centroid
    def move(lon, lat):
        x = (lon - uc.x) * math.cos(math.radians(lat)); y = lat - uc.y
        nlat = cc.y + y; return [round(cc.x + x / math.cos(math.radians(nlat)), 3), round(nlat, 3)]
    data = {"wide": rings(L, box(40, 0, 160, 65), tol=0.04, min_area=0.02, nd=3),
            "usland": rings(L, box(-135, 15, -55, 55), tol=0.04, min_area=0.02, nd=3),
            "chn": rings([chn], box(70, 15, 140, 56), tol=0.03, min_area=0.02, nd=3),
            "usOnChina": [[v for p in np.asarray(us.exterior.coords)[:-1] for v in move(*p)]],
            "usMain": rings([us], box(-130, 20, -60, 52), tol=0.05, nd=3),
            "places": {"beijing": [116.4, 39.9], "kashgar": [75.99, 39.47], "urumqi": [87.6, 43.8], "shanghai": [121.47, 31.23]}}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items() if isinstance(v, list)}, round(cmain.bounds[0], 1), round(cmain.bounds[2], 1))


if __name__ == "__main__":
    main()
