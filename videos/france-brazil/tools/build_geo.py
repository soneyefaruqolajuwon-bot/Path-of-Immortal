"""Export geometry (Natural Earth 10m, public domain) for the France–Brazil short to src/geo_data.js."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")


def line_flat(g):
    out = []
    for ln in getattr(g, "geoms", [g]):
        if ln.geom_type == "LineString" and len(ln.coords) > 1:
            out.append([round(v, 4) for xy in ln.coords for v in xy])
    return out


def main():
    L = land()
    world = rings(L, box(-100, -40, 45, 72), tol=0.05, min_area=0.05, nd=3)
    europe = rings(L, box(-25, 30, 40, 72), tol=0.01, min_area=0.002, nd=4)
    guiana = rings(L, box(-82, -40, -32, 14), tol=0.004, smooth=1, min_area=0.0005, nd=4)
    C = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] in ("FRA", "ESP", "DEU", "BRA", "SUR", "BEL", "ITA", "CHE"):
            C[rec.record["ADM0_A3"]] = shape(rec.shape.__geo_interface__)
    fra = C["FRA"]
    countries = {
        "FRA_EU": rings([fra], box(-6, 41, 10, 52), tol=0.01, min_area=0.002, nd=4),
        "GUF": rings([fra], box(-55, 1.5, -51, 6.2), tol=0.004, smooth=1, min_area=0.0005, nd=4),
        "ESP": rings([C["ESP"]], box(-10, 35, 5, 44.5), tol=0.01, min_area=0.002, nd=4),
        "DEU": rings([C["DEU"]], box(5, 47, 16, 56), tol=0.01, min_area=0.002, nd=4),
        "BRA": rings([C["BRA"]], box(-75, -34, -34, 6), tol=0.02, min_area=0.002, nd=3),
        "SUR": rings([C["SUR"]], box(-59, 1.5, -53.9, 6.2), tol=0.004, min_area=0.002, nd=4),
    }
    fra_esp = line_flat(fra.boundary.intersection(C["ESP"].buffer(0.03)).intersection(box(-2.5, 42.2, 3.4, 43.5)))
    guf_bra = line_flat(fra.boundary.intersection(C["BRA"].buffer(0.03)).intersection(box(-55, 1.5, -51, 4.6)))
    data = {"world": world, "europe": europe, "guiana": guiana, "countries": countries, "fraEsp": fra_esp, "gufBra": guf_bra,
            "paris": [2.35, 48.86], "cayenne": [-52.33, 4.92], "kourou": [-52.65, 5.16]}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in countries.items()}, "fraEsp", len(fra_esp), "gufBra", len(guf_bra))


if __name__ == "__main__":
    main()
