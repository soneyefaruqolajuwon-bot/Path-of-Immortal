"""Export Persian Gulf geometry (Natural Earth 10m, public domain) to src/geo_data.js.

  land      - coastline rings (lightly smoothed) for the whole Gulf region
  countries - per-country polygons (ISO3 -> rings) for highlights / Musandam
  borders   - land boundary polylines
  lanes     - approximate Strait of Hormuz traffic-separation lanes (illustrative)
"""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")
BOX = box(40.0, 18.0, 66.0, 35.0)
ISO = ["IRN", "SAU", "IRQ", "KWT", "QAT", "ARE", "OMN", "BHR"]


def main():
    L = land()
    land_r = rings(L, BOX, tol=0.004, smooth=1, min_area=0.0004, nd=4)
    countries = {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        iso = rec.record["ADM0_A3"]
        if iso in ISO:
            countries[iso] = rings([shape(rec.shape.__geo_interface__)], BOX, tol=0.004, smooth=1, min_area=0.0004, nd=4)
    borders = []
    for s in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_boundary_lines_land.shp")).shapes():
        g = shape(s.__geo_interface__)
        if not g.intersects(BOX):
            continue
        g = g.intersection(BOX).simplify(0.003)
        for ln in getattr(g, "geoms", [g]):
            if ln.geom_type == "LineString" and len(ln.coords) > 1:
                borders.append([round(v, 4) for xy in ln.coords for v in xy])
    # Illustrative two-lane traffic separation scheme curving around Musandam (inbound + outbound, ~2 nmi each)
    centre = [[54.9, 26.05], [55.6, 26.3], [56.05, 26.5], [56.32, 26.6], [56.55, 26.53], [56.75, 26.3], [56.95, 25.95], [57.3, 25.55]]
    data = {"land": land_r, "countries": countries, "borders": borders, "laneCentre": centre}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(land_r), {k: len(v) for k, v in countries.items()}, len(borders))


if __name__ == "__main__":
    main()
