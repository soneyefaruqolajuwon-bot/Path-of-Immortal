"""World geometry (Natural Earth 10m, public domain) as lon/lat rings for the projection-morphing engine."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape, Polygon, MultiPolygon
from shapely.ops import unary_union
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, "..", ".cache")
WORLD = box(-180, -85, 180, 85)


def flat(geom, tol, min_area=0.05):
    return rings([geom], WORLD, tol=tol, min_area=min_area, nd=2)


def main():
    world = rings(land(), WORLD, tol=0.12, min_area=0.15, nd=2)
    C, africa = {}, []
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        g = shape(rec.shape.__geo_interface__)
        iso = rec.record["ADM0_A3"]
        C[iso] = g
        if rec.record["CONTINENT"] == "Africa":
            africa.append(g.buffer(0.05))
    alaska = C["USA"].intersection(box(-170, 50, -129, 72))
    russia = C["RUS"].intersection(box(19, 40, 180, 82))
    out = {"world": world, "AFRICA": flat(unary_union(africa).simplify(0.1), 0.0, 0.3), "ALASKA": flat(alaska, 0.08)}
    for iso in ["GRL", "DZA", "CAN", "MEX", "IND", "BRA", "IDN", "KEN", "COL", "NOR", "SWE", "FIN", "ATA"]:
        out[iso] = flat(C[iso], 0.08 if iso not in ("CAN", "ATA") else 0.15, 0.08)
    out["RUS"] = flat(russia, 0.15, 0.1)
    cent = {}
    for k, g in (("GRL", C["GRL"]), ("ALASKA", alaska), ("RUS", russia), ("CAN", C["CAN"])):
        p = g.representative_point() if k == "CAN" else g.centroid
        cent[k] = [round(p.x, 2), round(p.y, 2)]
    out["centroids"] = cent
    path = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(path, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(out, separators=(",", ":")) + ";\n")
    print(path, os.path.getsize(path) // 1024, "KB", {k: (sum(len(r) for r in v) // 2 if isinstance(v, list) else v) for k, v in out.items()})


if __name__ == "__main__":
    main()
