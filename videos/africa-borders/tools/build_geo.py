"""Africa + Europe geometry (Natural Earth 10m, public domain) and the real shared borders used as highlight lines."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape, MultiLineString, LineString
from shapely.ops import linemerge
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__)); CACHE = os.path.join(HERE, "..", ".cache")
PAIRS = {"egy_sdn": ("EGY", "SDN"), "egy_lby": ("EGY", "LBY"), "lby_tcd": ("LBY", "TCD"), "mrt_mli": ("MRT", "MLI"), "dza_mli": ("DZA", "MLI"),
         "dza_mrt": ("DZA", "MRT"), "nam_bwa": ("NAM", "BWA"), "lby_dza": ("LBY", "DZA"), "dza_ner": ("DZA", "NER"), "sdn_tcd": ("SDN", "TCD"),
         "esh_mrt": ("ESH", "MRT"), "lby_ner": ("LBY", "NER"), "lby_sdn": ("LBY", "SDN"), "cod_cog": ("COD", "COG"), "nam_zaf": ("NAM", "ZAF"),
         "mli_ner": ("MLI", "NER")}
STRAIGHT = ["egy_sdn", "egy_lby", "lby_tcd", "mrt_mli", "dza_mli", "dza_mrt", "nam_bwa", "lby_ner", "lby_sdn", "esh_mrt", "dza_ner", "lby_dza"]
NATURAL = ["cod_cog", "nam_zaf"]


def lines_of(g):
    g = linemerge(g) if g.geom_type in ("MultiLineString",) else g
    out = []
    for part in (getattr(g, "geoms", None) or [g]):
        if part.geom_type == "LineString" and part.length > 0.3:
            s = part.simplify(0.02)
            out.append([[round(x, 3), round(y, 3)] for x, y in s.coords])
    return out


def main():
    L = land()
    world = rings(L, box(-45, -45, 150, 75), tol=0.04, min_area=0.03, nd=3)
    shapes, africa, europe = {}, {}, {}
    for rec in shapefile.Reader(os.path.join(CACHE, "ne_10m_admin_0_countries.shp")).shapeRecords():
        iso, cont = rec.record["ADM0_A3"], rec.record["CONTINENT"]
        if cont == "Africa" or iso in ("GBR", "FRA", "DEU", "BEL", "PRT", "ESP", "ITA", "NLD"):
            g = shape(rec.shape.__geo_interface__).buffer(0)
            shapes[iso] = g
            target = africa if cont == "Africa" else europe
            target[iso] = rings([g], box(-32, -42, 70, 72), tol=0.03, min_area=0.02, nd=3)
    borders = {}
    for key, (a, b) in PAIRS.items():
        if a in shapes and b in shapes:
            inter = shapes[a].boundary.intersection(shapes[b].boundary)
            if not inter.is_empty: borders[key] = lines_of(inter)
    # Caprivi Strip: Namibia's eastern finger
    cap = shapes["NAM"].intersection(box(21.4, -18.6, 25.4, -17.2))
    data = {"world": world, "africa": africa, "europe": europe, "borders": borders, "straight": STRAIGHT, "natural": NATURAL,
            "caprivi": rings([cap], box(20, -20, 26, -16), tol=0.01, min_area=0.0, nd=3)}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB; africa", len(africa), "europe", len(europe), "borders", {k: sum(len(l) for l in v) for k, v in borders.items()})


if __name__ == "__main__":
    main()
