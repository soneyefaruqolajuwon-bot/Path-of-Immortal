"""New York State, US states, Great Lakes, Hudson & Mohawk (Natural Earth 10m, public domain).
The two rivers are hand-traced centrelines through real towns (accurate to a few km at state scale)."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); V = os.path.join(HERE, "..", "..")
CB = os.path.join(V, "canberra", ".cache")
HUDSON = [(-74.03, 40.60), (-74.02, 40.70), (-73.95, 40.85), (-73.90, 40.95), (-73.90, 41.07), (-73.95, 41.20), (-73.96, 41.29), (-73.95, 41.39), (-74.00, 41.50),
          (-73.94, 41.70), (-73.96, 41.93), (-73.93, 42.08), (-73.86, 42.22), (-73.79, 42.36), (-73.75, 42.55), (-73.74, 42.65), (-73.69, 42.73), (-73.67, 42.79),
          (-73.66, 42.90), (-73.59, 43.27), (-73.85, 43.55), (-74.05, 43.85)]
MOHAWK = [(-73.68, 42.78), (-73.80, 42.80), (-73.95, 42.82), (-74.19, 42.94), (-74.57, 42.90), (-74.86, 43.04), (-74.99, 43.03), (-75.23, 43.10), (-75.46, 43.21)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    st = {}
    for rec in shapefile.Reader(os.path.join(CB, "adm1", "ne_10m_admin_1_states_provinces.shp")).shapeRecords():
        if rec.record["iso_a2"] == "US" and rec.record["postal"] not in ("AK", "HI"):
            st[rec.record["postal"]] = shape(rec.shape.__geo_interface__).buffer(0)
    lakes = []
    for rec in shapefile.Reader(os.path.join(V, "canada-long", ".cache", "ne_10m_lakes.shp")).shapeRecords():
        g = shape(rec.shape.__geo_interface__)
        if g.area > 0.15 and g.intersects(box(-93, 40, -72, 50)): lakes.extend(getattr(g, "geoms", [g]))
    data = {"wide": rings(L, box(-130, 22, -60, 52), tol=0.02, min_area=0.01, nd=3),
            "lakes": rings(lakes, box(-93, 40, -72, 50), tol=0.01, min_area=0.05, nd=3),
            "ny": rings([st["NY"]], box(-80, 40, -71, 46), tol=0.004, min_area=0.002, nd=4),
            "hudson": [[c for p in HUDSON for c in p]], "mohawk": [[c for p in MOHAWK for c in p]]}
    for k, g in st.items():
        data["st_" + k] = rings([g], box(-130, 22, -60, 52), tol=0.03 if k != "NY" else 0.01, min_area=0.004, nd=3)
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); rivers hand-traced\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", len(st), "states", len(data["lakes"]), "lakes")


if __name__ == "__main__":
    main()
