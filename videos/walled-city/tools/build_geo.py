"""Export map geometry (Natural Earth 10m land, public domain) to src/geo_data.js.

  region - South China coast (simplified) for the 1898 lease shot
  hk     - Hong Kong detail (smoothed) for close-ups
  nt     - the 1898 leased area (New Territories + New Kowloon): land between Boundary Street and the Shenzhen River
"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import land, rings  # noqa: E402
from shapely.geometry import box, Polygon

HERE = os.path.dirname(os.path.abspath(__file__))
WALLED_CITY = (114.1903, 22.3322)

def main():
    L = land()
    region = rings(L, box(108.0, 17.5, 121.0, 27.5), tol=0.01, min_area=0.0004, nd=3)
    hk = rings(L, box(113.75, 22.08, 114.55, 22.62), smooth=2, min_area=0.000005)
    # leased area: mainland north of Boundary Street (~22.33) up to the Shenzhen River (~22.53), plus the outlying
    # islands are left out for clarity; Hong Kong Island and the Kowloon tip stay unshaded.
    lease_box = Polygon([(113.82, 22.327), (114.45, 22.327), (114.45, 22.515), (114.08, 22.535), (113.95, 22.50), (113.82, 22.48)])
    nt = rings(L, lease_box, smooth=2, min_area=0.0001)
    data = {"region": region, "hk": hk, "nt": nt, "walledCity": WALLED_CITY}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    with open(out, "w") as f:
        f.write("// generated by tools/build_geo.py from Natural Earth 10m land (public domain)\n")
        f.write("const GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB", {k: len(v) for k, v in data.items() if isinstance(v, list)})

if __name__ == "__main__":
    main()
