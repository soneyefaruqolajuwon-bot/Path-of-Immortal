"""British Isles + nearby Europe land (Natural Earth 10m, public domain) and a hand-traced Thames through London."""
import json, os, sys
import shapefile
from shapely.geometry import box, shape
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "point-roberts", "tools"))
from build_geo import rings  # noqa: E402
HERE = os.path.dirname(os.path.abspath(__file__)); CB = os.path.join(HERE, "..", "..", "canberra", ".cache")
THAMES = [(-0.42, 51.44), (-0.31, 51.46), (-0.25, 51.475), (-0.19, 51.48), (-0.15, 51.485), (-0.12, 51.502), (-0.09, 51.508), (-0.06, 51.505), (-0.035, 51.50),
          (-0.02, 51.49), (-0.005, 51.485), (0.005, 51.497), (0.015, 51.505), (0.04, 51.50), (0.07, 51.505), (0.11, 51.50), (0.17, 51.49), (0.24, 51.47), (0.33, 51.46)]


def main():
    L = []
    for s in shapefile.Reader(os.path.join(CB, "ne_10m_land.shp")).shapes():
        g = shape(s.__geo_interface__); L.extend(getattr(g, "geoms", [g]))
    gbr = None
    for rec in shapefile.Reader(os.path.join(CB, "ne_10m_admin_0_countries.shp")).shapeRecords():
        if rec.record["ADM0_A3"] == "GBR": gbr = shape(rec.shape.__geo_interface__).buffer(0)
    data = {"wide": rings(L, box(-14, 46, 12, 62), tol=0.01, min_area=0.002, nd=3),
            "gbr": rings([gbr], box(-9, 49, 3, 61), tol=0.01, min_area=0.002, nd=3),
            "thames": [[c for p in THAMES for c in p]]}
    out = os.path.join(HERE, "..", "src", "geo_data.js")
    open(out, "w").write("// generated by tools/build_geo.py from Natural Earth 10m (public domain); Thames hand-traced\nconst GEO = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(out, os.path.getsize(out) // 1024, "KB")


if __name__ == "__main__":
    main()
